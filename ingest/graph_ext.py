def _sg(s: str) -> str:
    return "t4sg_" + s[3:] if s.startswith("t4_") else s


def _mirror_refs(refs: list, replace: bool = False) -> list:
    """replace=True: a T4SG twin (T4 refs become T4SG refs). Otherwise: T4 refs are kept and a T4SG copy is added."""
    out = []
    for r in refs:
        pl, ref = r["plans"], r["ref"]
        literal_t4 = ref.startswith("t4_") and (pl is None or pl == ["t4"] or ("t4" in pl and "{p}" not in ref))
        if replace:
            out.append({"plans": None if pl is None else ["t4sg"], "ref": _sg(ref)} if literal_t4 else r)
            continue
        out.append(r)
        if literal_t4:
            out.append({"plans": None if pl is None else ["t4sg"], "ref": _sg(ref)})
        elif pl and "t4" in pl and "{p}" in ref and "t4sg" not in pl:
            r["plans"] = pl + ["t4sg"]
    return out


def _mirror_ids(ids: list) -> list:
    out = []
    for x in ids:
        out.append(x)
        if isinstance(x, dict) and "t4" in x["plans"]:
            if "{p}" in x["id"]:
                x["plans"] = x["plans"] + ["t4sg"]
            elif x["id"].endswith("_t4"):
                out.append({"plans": ["t4sg"], "id": x["id"] + "sg"})
        elif isinstance(x, str) and x.endswith("_t4"):
            out.append(x + "sg")
    return out


def _mirror_t4() -> None:
    twins = []
    for t in NEW_DETAILS:
        if "{p}" in t["id"]:
            if "t4" in t["plans"]:
                t["plans"] = t["plans"] + ["t4sg"]
                t["refs"] = _mirror_refs(t["refs"])
        elif t["plans"] == ["t4"] and t["id"].endswith("_t4"):
            twin = {**t, "id": t["id"] + "sg", "plans": ["t4sg"], "refs": _mirror_refs(t["refs"], replace=True),
                    "desc": t["desc"].replace("ประเภท 4", "ประเภท 4 ป้องกันภัย")}
            twins.append(twin)
    NEW_DETAILS.extend(twins)
    for rows, id_key in ((EVENTS, "triggers"), (ROLES, "applies"), (USAGES, "applies"), (DRIVER_STATES, "applies"),
                         (FAULTS, "applies"), (DEFS, None), (DEADLINES, None), (RECOVERY, "applies")):
        for n in rows:
            n["refs"] = _mirror_refs(n["refs"])
            if id_key:
                n[id_key] = _mirror_ids(n[id_key])


