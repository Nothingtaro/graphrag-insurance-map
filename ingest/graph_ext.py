def attach(grants: dict, new: dict) -> None:
    """Hang the new per-prefix details on the coverage cells they belong to (see COV_LIMIT)."""
    for t in NEW_DETAILS:
        for p, did in _instances(t):
            if did not in new or p is None:
                continue
            secs = {_section(r) for r in new[did]["clauses"]}
            parent = new[did].get("exceptionOf")
            for pid in PLANS_OF.get(p, []):
                for cov, cell in grants.get(pid, {}).items():
                    if cell["s"] == "N" or cov not in COV_LIMIT.get(t["id"], [cov]):
                        continue
                    if parent and parent not in cell["details"]:   # an exception sits next to the exclusion it lifts
                        continue
                    if secs & {_section(r) for r in cell["clauses"]} and did not in cell["details"]:
                        cell["details"].append(did)


def cmi_grants(g) -> dict:
    """พ.ร.บ. as a plan column. `g` is graph.g (passed in to avoid a circular import)."""
    rows = {r["cov"]: r for r in CMI_GRANTS}
    to_pa = ["cmi_family", "cmi_driver", "cmi_init_med", "cmi_init_loss", "cmi_init_death"]
    to_bi = [t["id"] for t in CMI_NODES if t["id"] not in ("cmi_family", "cmi_driver")]
    out = {}
    for cov in ["bi", "pd", "col", "nocp", "flood", "theft", "fire", "pa"]:
        if cov in ("col", "nocp", "flood", "theft", "fire"):
            out[cov] = g("N", "ไม่คุ้มครองตัวรถ รถหาย หรือไฟไหม้", [], ["nood_cmi"])
        elif cov == "pd":
            out[cov] = g("N", rows["pd"]["sum"], [], ["nopd_cmi"])
        else:
            r = rows[cov]
            out[cov] = g(r["s"], r["sum"], _all_refs(r["refs"]), to_bi if cov == "bi" else to_pa)
    return out


def _expand_ids(ids: list, known: set) -> list[str]:
    out = []
    for x in ids:
        if isinstance(x, dict):   # {"plans": [...], "id": template}
            cand = [x["id"].replace("{p}", p) for p in x["plans"]] if "{p}" in x["id"] else [x["id"]]
        else:
            cand = [x.replace("{p}", p) for p in PREFIXES] if "{p}" in x else [x]
        out += [c for c in cand if c in known and c not in out]
    return out


def _interp(x: dict) -> str | None:
    v = x.get("interp")
    return v if isinstance(v, str) and v else None


def nodes(known: set) -> dict:
    """Events, factors, definitions, deadlines, recovery with concrete detail ids and refs (refs resolved by build_data)."""
    events = [{"id": e["id"], "name": e["name"], "syn": e["syn"], "covs": e["maps"], "desc": e["desc"], "interp": _interp(e),
               "details": _expand_ids(e["triggers"], known), "refs": _all_refs(e["refs"]),
               "topics": [e["topic"]] if e.get("topic") else []}
              for e in EVENTS]
    factors = []
    for typ, rows in (("role", ROLES), ("usage", USAGES), ("driver_state", DRIVER_STATES), ("fault", FAULTS)):
        for f in rows:
            factors.append({"id": f["id"], "type": typ, "name": f["name"], "syn": f["syn"], "desc": f["desc"], "interp": _interp(f),
                            "details": _expand_ids(f["applies"], known), "refs": _all_refs(f["refs"]),
                            "topics": f.get("topics") or ([f["topic"]] if f.get("topic") else [])})
    defs = [{"id": d["id"], "term": d["term"], "desc": d["desc"], "interp": _interp(d), "refs": _all_refs(d["refs"])} for d in DEFS]
    deadlines = [{"id": d["id"], "kind": d["kind"], "who": d["who"], "when": d["when"], "what": d["what"], "note": d.get("note"),
                  "refs": _all_refs(d["refs"])} for d in DEADLINES]
    recovery = [{"id": r["id"], "name": r["name"], "dir": r["dir"], "desc": r["desc"], "details": _expand_ids(r["applies"], known),
                 "refs": _all_refs(r["refs"])} for r in RECOVERY]
    return {"events": events, "factors": factors, "definitions": defs, "deadlines": deadlines, "recovery": recovery}
