def _sub(ref: str, p: str) -> str:
    """{p} -> prefix; {ry} -> endorsement prefix (ร.ย. "ry" in regular wordings, ร.ย.ฟ. "ryf" in EV wordings)."""
    return ref.replace("{p}", p).replace("{ry}", "ryf" if p.startswith("ev") else "ry")


def _refs(refs: list, p: str | None) -> list[str]:
    out = []
    for r in refs:
        if r["plans"] is None:
            out.append(r["ref"])
        elif p is not None and p in r["plans"]:
            out.append(_sub(r["ref"], p))
    return out


def _all_refs(refs: list) -> list[str]:
    """Every concrete ref of a node that is not per-plan (events, definitions ...)."""
    out = []
    for r in refs:
        for x in ([r["ref"]] if r["plans"] is None else [_sub(r["ref"], p) for p in r["plans"]]):
            if x not in out:
                out.append(x)
    return out


def _section(ref: str) -> str:
    m = re.match(r"([a-z0-9]+_(?:s\d+|rp\d+|g|ryf?\d+))", ref.split("@")[0])
    return m.group(1) if m else ref


